// Валідація ПІБ пацієнта для ПУБЛІЧНОГО онлайн-запису.
//
// Мета — не пускати в розклад очевидне сміття на кшталт «выв Володимир Павлівна»
// (набір клавіш у полі прізвища), але не відхиляти реальні імена. Тож:
//   • щонайменше 3 токени (прізвище, ім'я, по батькові);
//   • кожен токен ≥2 символів;
//   • лише літери української кирилиці ТА латиниці (для іноземних імен),
//     апостроф і дефіс — без цифр, символів і суто-російських літер
//     (ы/ъ/э/ё), які дає перемикання розкладки чи випадковий ввід.
// Нетипові написання (напр. з «ы») мають іти через реєстратуру — форма це прямо
// пропонує. Ідеально відсіяти будь-яку абракадабру без ризику для справжніх імен
// неможливо, тож головний захист від спаму — окремий guard дублів по телефону.

const NAME_TOKEN =
  /^[А-ЩЬЮЯҐЄІЇа-щьюяґєіїA-Za-z][А-ЩЬЮЯҐЄІЇа-щьюяґєіїA-Za-z'’ʼ-]*$/;

export function isPlausibleFullName(raw: unknown): boolean {
  const tokens = String(raw ?? "").trim().split(/\s+/).filter(Boolean);
  if (tokens.length < 3) return false;
  return tokens.every((token) => token.length >= 2 && NAME_TOKEN.test(token));
}
