const lc = (s: string) => (s || "").toLowerCase();

// Позиція токена, який зараз редагують, і його префікс.
// 0 — прізвище, 1 — ім'я, 2 — по батькові.
export function nameTokenAt(value: string): { idx: number; prefix: string } {
  const raw = value || "";
  const endsSpace = /\s$/.test(raw);
  const arr = raw.trim().length ? raw.trim().split(/\s+/) : [];
  const idx = endsSpace ? arr.length : Math.max(arr.length - 1, 0);
  const prefix = endsSpace ? "" : (arr[arr.length - 1] || "");
  return { idx, prefix };
}

// Підказки для поточного токена: імена для 2-го слова, по батькові — для 3-го.
export function nameSuggestions(value: string, limit = 8): string[] {
  const { idx, prefix } = nameTokenAt(value);
  const source = idx === 1 ? UKR_NAMES : idx === 2 ? UKR_PATRONYMICS : null;
  if (!source) return [];
  const pre = lc(prefix);
  return source.filter((s) => lc(s).indexOf(pre) === 0).slice(0, limit);
}

// Підставляє обране значення у відповідний токен; після імені лишає пробіл.
export function applyNameSuggestion(value: string, pick: string): string {
  const { idx } = nameTokenAt(value);
  const arr = (value || "").trim().length ? (value || "").trim().split(/\s+/) : [];
  const head = arr.slice(0, idx);
  head[idx] = pick;
  return head.join(" ") + (idx < 2 ? " " : "");
}
