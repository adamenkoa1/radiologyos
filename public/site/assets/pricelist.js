function getPricelist() {
  try {
    const saved = JSON.parse(localStorage.getItem(PRICELIST_STORE) || 'null');
    if (Array.isArray(saved) && saved.length) return saved;
  } catch (e) {}
  return JSON.parse(JSON.stringify(DEFAULT_PRICELIST));
}

function savePricelist(list) {
  localStorage.setItem(PRICELIST_STORE, JSON.stringify(list));
}

function resetPricelist() {
  localStorage.removeItem(PRICELIST_STORE);
}
